"""
@file results_controller.py
@author Mohamed EL BOUKHIARI
@brief Controller used to discover and parse experiment result files.
@details
This controller scans the project tree for result files generated by training,
testing and hyperparameter search workflows. It extracts summary information
from CSV and YAML files and provides normalized data to the ResultsPage.
"""

from __future__ import annotations

import csv
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ui.utils.resources import PROJECT_ROOT
from datetime import datetime

try:
    import yaml
except ImportError:
    yaml = None


@dataclass(frozen=True)
class ResultFileInfo:
    """
    @brief Metadata describing a discovered result file.
    """

    path: Path
    model: str
    kind: str
    description: str


@dataclass(frozen=True)
class ExperimentRecord:
    """
    @brief Normalized experiment metrics extracted from a result file.
    """

    model: str
    source_file: str
    rmse: float | None
    pearson: float | None
    spearman: float | None
    status: str
    trials: int
    path: Path


@dataclass(frozen=True)
class ResultsSummary:
    """
    @brief Full summary returned to the graphical results page.
    """

    result_files: list[ResultFileInfo]
    records: list[ExperimentRecord]
    total_files: int
    csv_files: int
    yaml_files: int
    total_trials: int
    best_rmse: float | None
    best_pearson: float | None
    best_spearman: float | None


class ResultsController:
    """
    @brief Controller responsible for experiment result discovery and parsing.
    """

    def __init__(self, project_root: Path = PROJECT_ROOT) -> None:
        """
        @brief Initialize the results controller.

        @param project_root Root directory of the project.
        """
        self.project_root = project_root

    def build_summary(self) -> ResultsSummary:
        """
        @brief Build a complete results summary.

        @return ResultsSummary containing discovered files, parsed metrics and counters.
        """
        result_files = self.discover_result_files()
        records = self.extract_experiment_records(result_files)

        csv_files = sum(1 for item in result_files if item.path.suffix.lower() == ".csv")
        yaml_files = sum(1 for item in result_files if item.path.suffix.lower() in {".yaml", ".yml"})
        total_trials = sum(record.trials for record in records)

        best_rmse = self._min_metric(record.rmse for record in records)
        best_pearson = self._max_metric(record.pearson for record in records)
        best_spearman = self._max_metric(record.spearman for record in records)

        return ResultsSummary(
            result_files=result_files,
            records=records,
            total_files=len(result_files),
            csv_files=csv_files,
            yaml_files=yaml_files,
            total_trials=total_trials,
            best_rmse=best_rmse,
            best_pearson=best_pearson,
            best_spearman=best_spearman,
        )

    def discover_result_files(self) -> list[ResultFileInfo]:
        """
        @brief Discover relevant result files inside the project tree.

        @return Sorted list of ResultFileInfo objects.
        """
        discovered_files: list[ResultFileInfo] = []

        ignored_directories = {
            ".git",
            "__pycache__",
            ".pytest_cache",
            ".mypy_cache",
            ".idea",
            ".vscode",
            "temp_runs",
            "Ligand_SDF",
            "Protein_PDB",
            "ALIGNED",
            "Graphs_EGNN",
            "Graphs_EDNN",
        }

        accepted_suffixes = {".csv", ".yaml", ".yml"}
        accepted_keywords = {
            "trials",
            "metrics_summary",
            "metrics_per_split",
            "best_config",
            "search_results",
        }

        for current_root, directories, filenames in os.walk(self.project_root):
            directories[:] = [
                directory
                for directory in directories
                if directory not in ignored_directories and not directory.startswith(".")
            ]

            current_path = Path(current_root)

            for filename in filenames:
                file_path = current_path / filename
                lower_name = filename.lower()

                if file_path.suffix.lower() not in accepted_suffixes:
                    continue

                if not any(keyword in lower_name for keyword in accepted_keywords):
                    continue

                discovered_files.append(
                    ResultFileInfo(
                        path=file_path,
                        model=self.detect_model(file_path),
                        kind=self.detect_file_kind(file_path),
                        description=self.build_file_description(file_path),
                    )
                )

        return sorted(discovered_files, key=lambda item: str(item.path).lower())

    def export_summary_csv(self, records: list[ExperimentRecord]) -> Path:
        """
        @brief Export parsed experiment records to a consolidated CSV file.
        @details
        The exported file contains one row per parsed experiment record and is
        stored in the project-level exports directory.

        @param records Experiment records to export.
        @return Path of the generated CSV file.
        """
        exports_dir = self.project_root / "exports"
        exports_dir.mkdir(parents=True, exist_ok=True)

        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        export_path = exports_dir / f"results_summary_{timestamp}.csv"

        fieldnames = [
            "model",
            "source_file",
            "rmse",
            "pearson",
            "spearman",
            "status",
            "trials",
            "path",
        ]

        with export_path.open("w", encoding="utf-8", newline="") as file:
            writer = csv.DictWriter(file, fieldnames=fieldnames)
            writer.writeheader()

            for record in records:
                writer.writerow(
                    {
                        "model": record.model,
                        "source_file": record.source_file,
                        "rmse": self._format_export_value(record.rmse),
                        "pearson": self._format_export_value(record.pearson),
                        "spearman": self._format_export_value(record.spearman),
                        "status": record.status,
                        "trials": record.trials,
                        "path": str(record.path),
                    }
                )

        return export_path

    def extract_experiment_records(
        self,
        result_files: list[ResultFileInfo],
    ) -> list[ExperimentRecord]:
        """
        @brief Extract normalized experiment records from discovered result files.

        @param result_files Discovered result files.
        @return List of normalized experiment records.
        """
        records: list[ExperimentRecord] = []

        for file_info in result_files:
            suffix = file_info.path.suffix.lower()

            if suffix == ".csv":
                record = self.extract_record_from_csv(file_info)
            elif suffix in {".yaml", ".yml"}:
                record = self.extract_record_from_yaml(file_info)
            else:
                record = None

            if record is not None:
                records.append(record)

        return records

    def extract_record_from_csv(self, file_info: ResultFileInfo) -> ExperimentRecord | None:
        """
        @brief Extract one normalized experiment record from a CSV file.

        @param file_info Result file metadata.
        @return ExperimentRecord if metrics could be extracted, otherwise None.
        """
        rows = self._read_csv_rows(file_info.path)

        if not rows:
            return None

        if "trials" in file_info.path.name.lower():
            return self._extract_record_from_trials_rows(file_info, rows)

        return self._extract_record_from_summary_rows(file_info, rows)

    def extract_record_from_yaml(self, file_info: ResultFileInfo) -> ExperimentRecord | None:
        """
        @brief Extract one normalized experiment record from a YAML file.

        @param file_info Result file metadata.
        @return ExperimentRecord if metrics could be extracted, otherwise None.
        """
        if yaml is None:
            return None

        try:
            content = yaml.safe_load(file_info.path.read_text(encoding="utf-8"))
        except Exception:
            return None

        if not isinstance(content, dict):
            return None

        best_metrics = content.get("best_metrics", {})
        best_trial = content.get("best_trial", {})

        if not isinstance(best_metrics, dict):
            best_metrics = {}

        if not isinstance(best_trial, dict):
            best_trial = {}

        rmse = self._first_float_from_dict(
            best_metrics,
            ["rmse_mean", "rmse", "RMSE", "best_rmse"],
        )
        pearson = self._first_float_from_dict(
            best_metrics,
            ["pearson_mean", "pearson", "Pearson", "best_pearson"],
        )
        spearman = self._first_float_from_dict(
            best_metrics,
            ["spearman_mean", "spearman", "Spearman", "best_spearman"],
        )

        if rmse is None and pearson is None and spearman is None:
            return None

        status = str(content.get("status", "selected"))

        return ExperimentRecord(
            model=file_info.model,
            source_file=file_info.path.name,
            rmse=rmse,
            pearson=pearson,
            spearman=spearman,
            status=status,
            trials=1 if best_trial else 0,
            path=file_info.path,
        )

    def detect_model(self, path: Path) -> str:
        """
        @brief Detect the model name from a result file path.

        @param path Result file path.
        @return Detected model name.
        """
        path_text = str(path).lower()

        if "egnn" in path_text:
            return "EGNN"
        if "ednn" in path_text:
            return "EDNN"
        if "deepdta" in path_text:
            return "DeepDTA"
        if "widedta" in path_text:
            return "WideDTA"
        if "urvdeeptaf" in path_text:
            return "URVDEEPTAF"

        return "Experiment"

    def detect_file_kind(self, path: Path) -> str:
        """
        @brief Detect the logical type of a result file.

        @param path Result file path.
        @return Result file kind.
        """
        name = path.name.lower()

        if "trials" in name:
            return "Trials"
        if "metrics_summary" in name:
            return "Metrics summary"
        if "metrics_per_split" in name:
            return "Split metrics"
        if "best_config" in name:
            return "Best configuration"

        return "Result file"

    def build_file_description(self, path: Path) -> str:
        """
        @brief Build a short description for a result file.

        @param path Result file path.
        @return Display description.
        """
        kind = self.detect_file_kind(path)

        descriptions = {
            "Trials": "Hyperparameter search trials table.",
            "Metrics summary": "Aggregated metrics summary.",
            "Split metrics": "Metrics reported for each split.",
            "Best configuration": "Best configuration selected by the experiment.",
        }

        return descriptions.get(kind, "Generated result file.")

    def _extract_record_from_trials_rows(
        self,
        file_info: ResultFileInfo,
        rows: list[dict[str, str]],
    ) -> ExperimentRecord:
        """
        @brief Extract best metrics from hyperparameter search trial rows.

        @param file_info Result file metadata.
        @param rows CSV rows.
        @return Normalized experiment record.
        """
        completed_rows = [
            row for row in rows
            if self._normalize_status(row.get("status", "")) not in {"failed", "error"}
        ]

        candidate_rows = completed_rows if completed_rows else rows
        best_row = self._select_best_rmse_row(candidate_rows)

        rmse = self._first_float_from_dict(
            best_row,
            ["rmse_mean", "rmse", "test_rmse", "validation_rmse", "val_rmse", "objective_value"],
        )
        pearson = self._first_float_from_dict(
            best_row,
            ["pearson_mean", "pearson", "test_pearson", "validation_pearson"],
        )
        spearman = self._first_float_from_dict(
            best_row,
            ["spearman_mean", "spearman", "test_spearman", "validation_spearman"],
        )

        status = self._normalize_status(best_row.get("status", "completed"))

        return ExperimentRecord(
            model=file_info.model,
            source_file=file_info.path.name,
            rmse=rmse,
            pearson=pearson,
            spearman=spearman,
            status=status,
            trials=len(rows),
            path=file_info.path,
        )

    def _extract_record_from_summary_rows(
        self,
        file_info: ResultFileInfo,
        rows: list[dict[str, str]],
    ) -> ExperimentRecord | None:
        """
        @brief Extract metrics from generic summary CSV rows.

        @param file_info Result file metadata.
        @param rows CSV rows.
        @return Normalized experiment record if metrics exist, otherwise None.
        """
        first_row = rows[0]

        rmse = self._first_float_from_dict(
            first_row,
            ["rmse_mean", "rmse", "RMSE", "test_rmse", "validation_rmse"],
        )
        pearson = self._first_float_from_dict(
            first_row,
            ["pearson_mean", "pearson", "Pearson", "test_pearson"],
        )
        spearman = self._first_float_from_dict(
            first_row,
            ["spearman_mean", "spearman", "Spearman", "test_spearman"],
        )

        if rmse is None and pearson is None and spearman is None:
            metric_map = self._extract_metric_value_map(rows)
            rmse = metric_map.get("rmse")
            pearson = metric_map.get("pearson")
            spearman = metric_map.get("spearman")

        if rmse is None and pearson is None and spearman is None:
            return None

        return ExperimentRecord(
            model=file_info.model,
            source_file=file_info.path.name,
            rmse=rmse,
            pearson=pearson,
            spearman=spearman,
            status="completed",
            trials=len(rows),
            path=file_info.path,
        )

    def _read_csv_rows(self, path: Path) -> list[dict[str, str]]:
        """
        @brief Read a CSV file as dictionaries.

        @param path CSV file path.
        @return List of CSV rows.
        """
        try:
            with path.open("r", encoding="utf-8", newline="") as file:
                reader = csv.DictReader(file)
                return [dict(row) for row in reader]
        except Exception:
            return []

    def _select_best_rmse_row(self, rows: list[dict[str, str]]) -> dict[str, str]:
        """
        @brief Select the row with the lowest RMSE value.

        @param rows Candidate rows.
        @return Best row according to RMSE, or first row if RMSE is unavailable.
        """
        best_row = rows[0]
        best_rmse = None

        for row in rows:
            rmse = self._first_float_from_dict(
                row,
                ["rmse_mean", "rmse", "test_rmse", "validation_rmse", "val_rmse", "objective_value"],
            )

            if rmse is None:
                continue

            if best_rmse is None or rmse < best_rmse:
                best_rmse = rmse
                best_row = row

        return best_row

    def _extract_metric_value_map(self, rows: list[dict[str, str]]) -> dict[str, float]:
        """
        @brief Extract metric values from rows formatted as metric-name/value pairs.

        @param rows CSV rows.
        @return Mapping from normalized metric names to values.
        """
        metric_map: dict[str, float] = {}

        metric_keys = ["metric", "Metric", "name", "Name"]
        value_keys = ["value", "Value", "mean", "Mean", "average", "Average"]

        for row in rows:
            metric_name = self._first_string_from_dict(row, metric_keys)
            value = self._first_float_from_dict(row, value_keys)

            if metric_name is None or value is None:
                continue

            normalized_name = metric_name.lower()

            if "rmse" in normalized_name:
                metric_map["rmse"] = value
            elif "pearson" in normalized_name:
                metric_map["pearson"] = value
            elif "spearman" in normalized_name:
                metric_map["spearman"] = value

        return metric_map

    def _first_float_from_dict(
        self,
        data: dict[str, Any],
        keys: list[str],
    ) -> float | None:
        """
        @brief Return the first valid float from a dictionary.

        @param data Source dictionary.
        @param keys Candidate keys.
        @return Parsed float value or None.
        """
        for key in keys:
            if key not in data:
                continue

            value = self._safe_float(data.get(key))

            if value is not None:
                return value

        return None

    def _first_string_from_dict(
        self,
        data: dict[str, Any],
        keys: list[str],
    ) -> str | None:
        """
        @brief Return the first non-empty string from a dictionary.

        @param data Source dictionary.
        @param keys Candidate keys.
        @return String value or None.
        """
        for key in keys:
            value = data.get(key)

            if value is None:
                continue

            text = str(value).strip()

            if text:
                return text

        return None

    def _safe_float(self, value: Any) -> float | None:
        """
        @brief Safely convert a value to float.

        @param value Value to convert.
        @return Float value or None.
        """
        if value is None:
            return None

        try:
            text = str(value).strip()

            if not text or text.lower() in {"nan", "none", "null", "-"}:
                return None

            return float(text)
        except (TypeError, ValueError):
            return None

    def _format_export_value(self, value: float | None) -> str:
        """
        @brief Format a metric value for CSV export.

        @param value Metric value.
        @return Formatted value or empty string.
        """
        if value is None:
            return ""

        return f"{value:.6f}"

    def _normalize_status(self, status: str) -> str:
        """
        @brief Normalize experiment status text.

        @param status Raw status.
        @return Normalized status.
        """
        normalized = str(status).strip().lower()

        if normalized in {"completed", "complete", "success", "ok", "done"}:
            return "completed"
        if normalized in {"failed", "failure", "error", "crashed"}:
            return "failed"
        if normalized in {"running", "started"}:
            return "running"

        return normalized or "unknown"

    def _min_metric(self, values: object) -> float | None:
        """
        @brief Return the minimum non-null metric value.

        @param values Iterable metric values.
        @return Minimum value or None.
        """
        valid_values = [value for value in values if value is not None]
        return min(valid_values) if valid_values else None

    def _max_metric(self, values: object) -> float | None:
        """
        @brief Return the maximum non-null metric value.

        @param values Iterable metric values.
        @return Maximum value or None.
        """
        valid_values = [value for value in values if value is not None]
        return max(valid_values) if valid_values else None
